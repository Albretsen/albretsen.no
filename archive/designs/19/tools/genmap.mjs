function inside(x, y, p) {
  let c = false
  for (let i = 0, j = p.length - 1; i < p.length; j = i++) {
    const [xi, yi] = p[i], [xj, yj] = p[j]
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c
  }
  return c
}

const COLS = 120, ROWS = 46
let d = '', count = 0
const rows = []
for (let j = 0; j < ROWS; j++) {
  const lat = 81 - 1.5 - 3 * j
  let row = ''
  for (let i = 0; i < COLS; i++) {
    const lon = -180 + 1.5 + 3 * i
    let hit = 0
    for (const [dx, dy] of [[0, 0], [-0.9, -0.9], [0.9, 0.9], [-0.9, 0.9], [0.9, -0.9]])
      if (polys.some(p => inside(lon + dx, lat + dy, p))) hit++
    const land = hit >= 2
    row += land ? '#' : '.'
    if (land) count++
  }
  rows.push(row)
  // runs of land become one dashed segment (stroke-dasharray 0 10, round caps = a dot every cell)
  for (const m of row.matchAll(/#+/g)) d += `M${5 + 10 * m.index} ${5 + 10 * j}h${10 * (m[0].length - 1)}`
}
