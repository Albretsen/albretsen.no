// Builds albretsen.no into dist/. Run: node scripts/build.ts
// Pages are rendered to static HTML with their CSS inlined; static assets are
// copied; every page gets a Markdown twin; budgets are checked at the end.
import { cp, mkdir, readFile, readdir, rename, rm, stat, writeFile } from 'node:fs/promises'
import { existsSync, readFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { brotliCompressSync, constants } from 'node:zlib'
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { markdown, parseFront, stripTitle, esc } from '../site/markdown.ts'
import { home, buildPage, writePage, postPage, stackPage, notFound, factCase, TOWN, STACK, IMPORT_MAP, type Post } from '../site/templates.ts'
import { site, products, dayJob, mcpClients } from '../site/data.ts'

const ROOT = new URL('..', import.meta.url).pathname
const DIST = join(ROOT, 'dist')
const SITE = join(ROOT, 'site')
const ARTICLES = join(ROOT, 'articles')

const minifyCss = (css: string) => css.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\s+/g, ' ').replace(/\s*([{}:;,>])\s*/g, '$1').replace(/;}/g, '}').trim()
const css = async (...names: string[]) => minifyCss((await Promise.all(names.map((n) => readFile(join(SITE, 'styles', n), 'utf8')))).join('\n'))

async function write(path: string, text: string) {
  const full = join(DIST, path)
  await mkdir(dirname(full), { recursive: true })
  await writeFile(full, path.endsWith('.html') ? withAssets(text) : text)
}
const walk = async (dir: string): Promise<string[]> => (await Promise.all((await readdir(dir, { withFileTypes: true })).map((e) => e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)]))).flat()

/* ---------------------------------------------------------------- fingerprints */
// dist/_headers caches /assets/* for a year, so every asset carries a hash of its content in its
// name: /assets/fonts/federo-latin.woff2 -> /assets/fonts/federo-latin.3f9c0a1b2d.woff2. Pages are
// written with the plain paths; withAssets() swaps in the hashed ones and fails on any that is missing.
// JavaScript modules import each other by their plain paths, which the import map resolves.
const manifest = new Map<string, string>()
const HASHED = /\.[0-9a-f]{10}\.[a-z0-9]+$/
async function fingerprint(keep: (rel: string) => boolean) {
  for (const f of await walk(join(DIST, 'assets'))) {
    const rel = f.slice(DIST.length)
    if (HASHED.test(rel) || !keep(rel)) continue
    const h = createHash('sha256').update(await readFile(f)).digest('hex').slice(0, 10)
    const out = rel.replace(/(\.[a-z0-9]+)$/i, `.${h}$1`)
    await rename(f, join(DIST, out))
    manifest.set(rel, out)
  }
}
const asset = (p: string) => { const h = manifest.get(p); if (!h) throw new Error(`no such asset: ${p}`); return h }
const withAssets = (html: string) => html.replace(/\/assets\/[\w\-./]+\.[a-z0-9]+/gi, asset).replace(IMPORT_MAP, importMap)
let importMap = ''
function makeImportMap() {
  const imports: Record<string, string> = {}
  for (const [k, v] of manifest) {
    if (!k.startsWith('/assets/town/') || !k.endsWith('.js')) continue
    imports[k] = v
    if (k === '/assets/town/vendor/three.module.min.js') imports.three = v
    const addon = /^\/assets\/town\/vendor\/addons\/(.+)$/.exec(k)
    if (addon) imports['three/addons/' + addon[1]] = v
  }
  importMap = `<script type="importmap">${JSON.stringify({ imports })}</script>`
}

// The town reads its facts from here: the same products, figures and lines as the pages, plus the
// fingerprinted URL of every logo and model it loads.
function townContent() {
  const models: Record<string, string> = {}
  for (const [k, v] of manifest) if (k.startsWith('/assets/town/models/')) models[k.slice('/assets/town/models/'.length)] = v
  const content = {
    person: site.person, company: site.company, domain: site.domain, email: site.email, location: site.location,
    line: site.line, availability: site.availability, mcpCommand: mcpClients[0].text,
    products: products.map((p) => ({ id: p.id, name: p.name, since: p.since, status: p.status, url: p.url, line: p.line, figure: p.figure, facts: p.facts?.map(factCase) })),
    logos: Object.fromEntries(Object.entries(TOWN).map(([id, t]) => [id, asset(t.logo)])),
  }
  return `// Generated by scripts/build.ts from site/data.ts. Do not edit.
export const content = ${JSON.stringify(content, null, 1)};
const MODELS = ${JSON.stringify(models, null, 1)};
/** The fingerprinted URL of a model: model('props/bench') or model('people/dog.glb'). */
export function model(name) { const u = MODELS[name.endsWith('.glb') ? name : name + '.glb']; if (!u) throw new Error('no model ' + name); return u; }
`
}

/* ---------------------------------------------------------------- articles */
async function loadPosts(): Promise<Post[]> {
  const entries = await readdir(ARTICLES, { withFileTypes: true })
  const files: { file: string; lang: 'en' | 'nb' }[] = []
  for (const e of entries) {
    if (e.isFile() && e.name.endsWith('.md')) files.push({ file: join(ARTICLES, e.name), lang: 'en' })
    if (e.isDirectory()) for (const lang of ['en', 'nb'] as const) if (existsSync(join(ARTICLES, e.name, `${lang}.md`))) files.push({ file: join(ARTICLES, e.name, `${lang}.md`), lang })
  }
  const posts: Post[] = []
  for (const { file, lang } of files) {
    const { front, body } = parseFront(await readFile(file, 'utf8'))
    const slug = String(front.slug)
    const path = lang === 'nb' ? `/nb/write/${slug}/` : `/write/${slug}/`
    const md = stripTitle(body)
    const html = markdown(md, (comment) => /interactive chart/i.test(comment) ? chartFigure(lang) : '')
    posts.push({ slug, lang, path, title: String(front.title), date: String(front.date), excerpt: String(front.excerpt ?? ''), tags: (front.tags as string[]) ?? [], html, md: body, alternates: [] })
  }
  for (const p of posts) p.alternates = posts.filter((q) => q.slug === p.slug).map((q) => ({ lang: q.lang, path: q.path })).sort((a, b) => (a.lang === 'en' ? -1 : 1))
  return posts.sort((a, b) => b.date.localeCompare(a.date) || a.title.localeCompare(b.title))
}

// The S&P chart: a static SVG first (same box as the live chart), the module when scrolled to.
const CHART_DIR = join(SITE, 'charts', 'spx')
const hasChart = () => ['chart.js', 'chart.css', 'build-data.ts'].every((f) => existsSync(join(CHART_DIR, f))) && !process.env.NO_CHART
function chartFigure(lang: 'en' | 'nb') {
  if (!hasChart()) return ''
  // The pre-rendered chart markup: the live module redraws it in exactly the same box.
  const shell = readFileSync(join(DIST, 'assets', 'charts', 'spx', `spx-shell.${lang}.html`), 'utf8')
  return `<div class="figure-wide spx-slot" data-spx data-lang="${lang}">${shell}</div>`
}
const CHART_SCRIPT = `<script type="module">const el=document.querySelector('[data-spx]');if(el){const go=async()=>{const{mountSpxChart}=await import('/assets/charts/spx/chart.js');mountSpxChart(el,{lang:el.dataset.lang,dataUrl:'/assets/charts/spx/spx.json'})};new IntersectionObserver((e,o)=>{if(e[0].isIntersecting){o.disconnect();go()}},{rootMargin:'600px'}).observe(el)}</script>`

